async function confirmNavigation(trigger, accept, type = 'confirm') {
  const count = browser.dialogs.length
  const pending = trigger()
  for (let i = 0; i < 100 && browser.dialogs.length === count; i++) await pause(30)
  assert.equal(browser.dialogs[count]?.type, type, 'Leaving a draft must request confirmation')
  await browser.send('Page.handleJavaScriptDialog', { accept })
  await pending
  await pause(100)
  assert.equal(browser.dialogs.length, count + 1, 'One action must open only one confirmation')
}

